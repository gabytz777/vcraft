module font

// An original 5x7 pixel font, authored here as binary pixel rows and packed
// into a single RGBA atlas. Like the block textures, there are no font files
// or external assets: text is just more procedurally generated pixel art.

// Glyph cell geometry. Each glyph is 5x7 pixels placed in a 6x8 cell so a
// one-pixel gap separates neighbouring characters.
pub const glyph_w = 5
pub const glyph_h = 7
pub const cell_w = 6
pub const cell_h = 8
pub const cols = 16
pub const first = 32 // ' '
pub const last = 126 // '~'
pub const atlas_w = 96 // cols * cell_w
pub const atlas_h = 48 // rows * cell_h

