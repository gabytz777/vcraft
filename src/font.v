// Expand every glyph into the atlas: opaque white pixels for set bits, fully
// transparent elsewhere. The renderer tints the white by the vertex colour.
pub fn build_font() []u8 {
	mut buf := []u8{len: atlas_w * atlas_h * 4}
	mut c := first
	for c <= last {
		rows := glyph(c)
		if rows.len > 0 {
			idx := c - first
			ox := (idx % cols) * cell_w
			oy := (idx / cols) * cell_h
			mut gy := 0
			for gy < glyph_h {
				bits := rows[gy]
				mut gx := 0
				for gx < glyph_w {
					if (bits >> u8(glyph_w - 1 - gx)) & 1 != 0 {
						o := ((oy + gy) * atlas_w + (ox + gx)) * 4
						buf[o] = 255
						buf[o + 1] = 255
						buf[o + 2] = 255
						buf[o + 3] = 255
					}
					gx++
				}
				gy++
			}
		}
		c++
	}
	return buf
}
